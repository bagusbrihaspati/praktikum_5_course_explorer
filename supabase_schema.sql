-- 1. Buat Tabel courses (Instruksi No. 64, 66, 67, 68)
CREATE TABLE IF NOT EXISTS public.courses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL,
  title text NOT NULL,
  credits integer NOT NULL,
  description text DEFAULT '',
  status text NOT NULL DEFAULT 'planned' CHECK (status IN ('planned', 'active', 'done')),
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Aktifkan Row Level Security (RLS) (Instruksi No. 69)
ALTER TABLE public.courses ENABLE ROW LEVEL SECURITY;

-- 3. Policy Permisif untuk kebutuhan praktikum laboratorium (Instruksi No. 69 & 70)
CREATE POLICY "Allow public read-write for lab"
ON public.courses
FOR ALL
TO anon, authenticated
USING (true)
WITH CHECK (true);

